// Converts VOCAB.PAS (word lists, room names, initial object placement) into C data for the MSX port.
//   node mkvocab.js <VOCAB.PAS> <out dir>      -> <out dir>/vocab_data.h, vocab_data.c
//
// The original assigns everything at startup, and the game later overwrites some entries
// (n[40], n[68], n[82], n[110], n[126]), so the runtime tables are RAM arrays of pointers to
// const strings, initialised by Vocab_Init(). Sets of objects (LSet = set of 1..133) become
// 17-byte bit arrays, bit (n-1) of byte (n-1)>>3.
const fs = require("fs");
const path = require("path");

const [srcFile, out] = process.argv.slice(2);
if (!srcFile || !out) { console.error("usage: node mkvocab.js <VOCAB.PAS> <out dir>"); process.exit(1); }
fs.mkdirSync(out, { recursive: true });

const V_MAX = 95, N_MAX = 133, P_MAX = 11, A_MAX = 4, R_MAX = 109;
const SET_BYTES = Math.ceil(N_MAX / 8);

const lists = { v: [], n: [], p: [], a: [], rn: [] };
const sets = Array.from({ length: R_MAX + 1 }, () => new Set());

// Pascal string literal -> JS string ('' is a quote)
function pstr(lit) {
	const m = /^'((?:[^']|'')*)'$/.exec(lit.trim());
	if (!m) throw new Error("bad string literal: " + lit);
	return m[1].replace(/''/g, "'");
}

// Pascal set expression: [1,5..7] | L[n] | L[n]+[..]
function evalSet(expr, line) {
	expr = expr.trim();
	let m = /^L\[(\d+)\]\s*(?:\+\s*(\[.*\]))?$/.exec(expr);
	if (m) {
		const s = new Set(sets[+m[1]]);
		if (m[2]) for (const x of parseList(m[2])) s.add(x);
		return s;
	}
	if (expr[0] === "[") return new Set(parseList(expr));
	throw new Error("cannot evaluate set: " + line);
}
function parseList(s) {
	const body = s.trim().slice(1, -1).trim();
	const r = [];
	if (!body) return r;
	for (const part of body.split(",")) {
		const m = /^\s*(\d+)(?:\s*\.\.\s*(\d+))?\s*$/.exec(part);
		if (!m) throw new Error("bad set element: " + part);
		const a = +m[1], b = m[2] ? +m[2] : a;
		for (let i = a; i <= b; i++) r.push(i);
	}
	return r;
}

for (let raw of fs.readFileSync(srcFile, "latin1").split(/\r?\n/)) {
	// strip trailing {comment} (only after the terminating ;)
	let line = raw.replace(/\s*\{[^}']*\}\s*$/, "").trim();
	let m;
	if ((m = /^(v|n|p|a)\[(\d+)\]:=('(?:[^']|'')*');$/.exec(line))) {
		lists[m[1]][+m[2]] = pstr(m[3]);
	} else if ((m = /^rn\[(\d+)\]:=('(?:[^']|'')*');$/.exec(line))) {
		lists.rn[+m[1]] = pstr(m[2]);
	} else if ((m = /^rn\[(\d+)\]:=rn\[(\d+)\];$/.exec(line))) {
		lists.rn[+m[1]] = lists.rn[+m[2]];
	} else if (/^for x:=1 to RMax do L\[x\]:=\[\];$/.test(line)) {
		for (let i = 1; i <= R_MAX; i++) sets[i] = new Set();
	} else if ((m = /^for x:=1 to RMax do L\[x\]:=L\[x\]\+(\[[^\]]*\]);$/.exec(line))) {
		for (let i = 1; i <= R_MAX; i++) for (const x of parseList(m[1])) sets[i].add(x);
	} else if ((m = /^L\[(\d+)\]:=(.*);$/.exec(line))) {
		sets[+m[1]] = evalSet(m[2], line);
	}
}

function check(name, arr, max) {
	for (let i = 1; i <= max; i++) if (arr[i] === undefined) throw new Error(name + "[" + i + "] missing");
	if (arr.length !== max + 1) throw new Error(name + " has " + (arr.length - 1) + " entries, expected " + max);
}
check("v", lists.v, V_MAX); check("n", lists.n, N_MAX); check("p", lists.p, P_MAX);
check("a", lists.a, A_MAX); check("rn", lists.rn, R_MAX);
for (const [k, s] of sets.entries()) for (const x of s) if (x < 1 || x > N_MAX) throw new Error("L[" + k + "] has " + x);

// ---- emit C ----
const strs = new Map(); // content -> name
function sref(s) {
	if (!strs.has(s)) strs.set(s, "s" + strs.size);
	return strs.get(s);
}
const cesc = s => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
function ptrArray(name, arr, max) {
	let t = "const char* const " + name + "[" + (max + 1) + "] = {\n\t0,";
	for (let i = 1; i <= max; i++) t += (i % 6 === 1 ? "\n\t" : " ") + sref(arr[i]) + ",";
	return t + "\n};\n";
}
const arrays = ptrArray("g_VInit", lists.v, V_MAX) + ptrArray("g_NInit", lists.n, N_MAX) +
	ptrArray("g_PInit", lists.p, P_MAX) + ptrArray("g_AInit", lists.a, A_MAX) + ptrArray("g_RNInit", lists.rn, R_MAX);

let locs = "const u8 g_LocInit[" + (R_MAX + 1) + "][VOCAB_SET_BYTES] = {\n";
for (let r = 0; r <= R_MAX; r++) {
	const b = new Array(SET_BYTES).fill(0);
	for (const x of sets[r]) b[(x - 1) >> 3] |= 1 << ((x - 1) & 7);
	locs += "\t{" + b.map(x => "0x" + x.toString(16).padStart(2, "0")).join(",") + "}," + (r ? " // room " + r : " // unused") + "\n";
}
locs += "};\n";

let strDefs = "";
let strBytes = 0;
for (const [s, name] of strs) { strDefs += "static const char " + name + "[] = \"" + cesc(s) + "\";\n"; strBytes += s.length + 1; }

const hdr = `// Generated by tools/mkvocab.js from VOCAB.PAS - do not edit
#pragma once
#include "../game/types.h"

#define VOCAB_V_MAX ${V_MAX}
#define VOCAB_N_MAX ${N_MAX}
#define VOCAB_P_MAX ${P_MAX}
#define VOCAB_A_MAX ${A_MAX}
#define VOCAB_R_MAX ${R_MAX}
#define VOCAB_SET_BYTES ${SET_BYTES}

// 1-based tables of pointers to word lists / names; entries may be repointed by the game
extern const char* g_V[VOCAB_V_MAX + 1];
extern const char* g_N[VOCAB_N_MAX + 1];
extern const char* g_P[VOCAB_P_MAX + 1];
extern const char* g_A[VOCAB_A_MAX + 1];
extern const char* g_RN[VOCAB_R_MAX + 1];

// g_Loc[room]: bit set of non-movable objects (object n = bit n-1)
extern u8 g_Loc[VOCAB_R_MAX + 1][VOCAB_SET_BYTES];

// Copies the initial tables into RAM (call once at start / on restart)
void Vocab_Init();

#define LOC_HAS(room, obj) (g_Loc[room][((obj) - 1) >> 3] & (1 << (((obj) - 1) & 7)))
#define LOC_ADD(room, obj) (g_Loc[room][((obj) - 1) >> 3] |= (1 << (((obj) - 1) & 7)))
#define LOC_DEL(room, obj) (g_Loc[room][((obj) - 1) >> 3] &= ~(1 << (((obj) - 1) & 7)))
`;

const csrc = `// Generated by tools/mkvocab.js from VOCAB.PAS - do not edit
// Original: Supernova (c) 1985, 1990, 2009 Apogee Software, Ltd. - GNU GPL v2 or later
#include "vocab_data.h"

${strDefs}
${arrays}
${locs}
const char* g_V[VOCAB_V_MAX + 1];
const char* g_N[VOCAB_N_MAX + 1];
const char* g_P[VOCAB_P_MAX + 1];
const char* g_A[VOCAB_A_MAX + 1];
const char* g_RN[VOCAB_R_MAX + 1];
u8 g_Loc[VOCAB_R_MAX + 1][VOCAB_SET_BYTES];

void Vocab_Init()
{
	u8 i;
	for (i = 0; i <= VOCAB_V_MAX; i++) g_V[i] = g_VInit[i];
	for (i = 0; i <= VOCAB_N_MAX; i++) g_N[i] = g_NInit[i];
	for (i = 0; i <= VOCAB_P_MAX; i++) g_P[i] = g_PInit[i];
	for (i = 0; i <= VOCAB_A_MAX; i++) g_A[i] = g_AInit[i];
	for (i = 0; i <= VOCAB_R_MAX; i++) g_RN[i] = g_RNInit[i];
	{
		const u8* s = (const u8*)g_LocInit;
		u8* d = (u8*)g_Loc;
		u16 n = sizeof(g_Loc);
		while (n--) *d++ = *s++;
	}
}
`;
fs.writeFileSync(path.join(out, "vocab_data.h"), hdr);
fs.writeFileSync(path.join(out, "vocab_data.c"), csrc);

const ptrs = (V_MAX + N_MAX + P_MAX + A_MAX + R_MAX + 5) * 2;
console.log("strings:", strs.size, "unique,", strBytes, "bytes; init pointer tables:", ptrs, "bytes (const) + same in RAM;",
	"set data:", (R_MAX + 1) * SET_BYTES, "bytes const + same in RAM");
